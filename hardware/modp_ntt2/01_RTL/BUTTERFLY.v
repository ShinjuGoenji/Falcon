module BUTTERFLY (
    // Input signals
    x,
    y,
    p,
    // Output signals
    X,
    Y,
);

//---------------------------------------------------------------------
//   Parameter & Integer
//---------------------------------------------------------------------
localparam P_WIDTH = 31;

//---------------------------------------------------------------------
//   Input & Output
//---------------------------------------------------------------------
input  [P_WIDTH-1:0] x;
input  [P_WIDTH-1:0] y;
input  [P_WIDTH-1:0] p;

output [P_WIDTH-1:0] X;
output [P_WIDTH-1:0] Y;

//---------------------------------------------------------------------
//   Submodule
//---------------------------------------------------------------------
MODP_ADD u_modp_add(.a(x), .b(y), .p(p), .d(X));
MODP_SUB u_modp_sub(.a(x), .b(y), .p(p), .d(Y));

endmodule