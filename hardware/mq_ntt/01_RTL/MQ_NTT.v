//---------------------------------------------------------------------
//   Reg & Wire
//---------------------------------------------------------------------
reg                        valid  [0:logn];
reg [Q_WIDTH-1:0]          a      [0:logn];

reg [Q_WIDTH-1:0]          s      [0:logn-1];
reg [Q_WIDTH-1:0]          s_reg  [0:logn-1];
reg [$clog2(LUT_SIZE)-1:0] tw_idx [0:logn-1];

//---------------------------------------------------------------------
//   Submodule
//---------------------------------------------------------------------
/*
 * The NTT pipeline is constructed by chaining `logn` (9) RADIX2 stages.
 * The output of one stage becomes the input for the next. Each stage `U`
 * receives its own twiddle factor stream.
 */
genvar stage_idx;
generate
    for (stage_idx = 0; stage_idx < logn; stage_idx++) begin
        RADIX2 #(logn, stage_idx+1, )
        u_RADIX2 (
            // Input signals
            .clk(clk), .rst_n(rst_n),
            .in_valid(valid[stage_idx]),
            .a_i(a[stage_idx]),
            .s(s_reg[stage_idx]),
            // Output signals
            .tw_idx(tw_idx[stage_idx]),
            .out_valid(valid[stage_idx+1]),
            .a_o(a[stage_idx+1])
        );
    end
endgenerate

genvar s_idx;
generate
    for (s_idx = 0; s_idx < logn; s_idx++) begin
        always @(*) begin
            s[s_idx] <= GMb[tw_idx[s_idx]];
        end
    end
endgenerate

assign out_valid = valid[logn];
assign a_o = a[logn];

//---------------------------------------------------------------------
//   Sequential Logic
//---------------------------------------------------------------------
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        valid[0] <= 0;
        a[0] <= 0;
    end
    else begin
        valid[0] <= in_valid;
        a[0] <= a_i;
    end
end

genvar s_reg_idx;
generate
    for (s_reg_idx = 0; s_reg_idx < logn; s_reg_idx++) begin
        always @(posedge clk or negedge rst_n) begin
            if (!rst_n) begin
                s_reg[s_reg_idx] <= 0;
            end
            else begin
                s_reg[s_reg_idx] <= s[s_reg_idx];
            end
        end
    end
endgenerate

endmodule
