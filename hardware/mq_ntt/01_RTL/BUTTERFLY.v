module BUTTERFLY (
    // Input signals
    x,
    y,
    // Output signals
    X,
    Y,
);

//---------------------------------------------------------------------
//   Parameter & Integer
//---------------------------------------------------------------------
localparam Q_WIDTH = 14;

//---------------------------------------------------------------------
//   Input & Output
//---------------------------------------------------------------------
input  [Q_WIDTH-1:0] x;
input  [Q_WIDTH-1:0] y;

output [Q_WIDTH-1:0] X;
output [Q_WIDTH-1:0] Y;

//---------------------------------------------------------------------
//   Submodule
//---------------------------------------------------------------------
MQ_ADD u_mq_add(.x(x), .y(y), .d(X));
MQ_SUB u_mq_sub(.x(x), .y(y), .d(Y));

endmodule