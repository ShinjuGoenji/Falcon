/*
 * Compute R = 2^31 mod p.
 */
module MODP_R (
    // Input signals
    p,
    // Output signals
    R
);

//---------------------------------------------------------------------
//   Parameter & Integer
//---------------------------------------------------------------------
localparam P_WIDTH = 31;

//---------------------------------------------------------------------
//   Input & Output
//---------------------------------------------------------------------
input  [P_WIDTH-1:0] p;
output [P_WIDTH-1:0] R;

//---------------------------------------------------------------------
//   Combinational Logic
//---------------------------------------------------------------------
assign R = (1 << 31) - p;

endmodule
